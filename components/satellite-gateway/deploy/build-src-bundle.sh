#!/bin/bash
#
# Builds the source bundle that gets shipped to a Satellite Gateway host.
#
# The gateway is developed as one component of a monorepo but compiled as a
# single Go module on the host. Two transformations are therefore required, and
# doing them by hand has caused drift between the repo and running hosts before:
#
#   1. internal/ is re-rooted under internal/satellite/ to match the
#      github.com/m2p/clm/internal/satellite/... import paths, with
#      internal/runtime/*.go moving up to internal/satellite/ (package
#      satellite) and vsatellite-coordinator renamed to vsatellite.
#   2. internal/core is copied in from the control plane, which owns the shared
#      interfaces.
#
# Usage: deploy/build-src-bundle.sh [output.tar.gz]
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTROL_PLANE="$(cd "$HERE/../saas-control-plane" && pwd)"
OUT="${1:-/tmp/clm-gateway-src.tar.gz}"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

echo "staging gateway source in $STAGE"

# Top-level files that keep their paths.
cp -R "$HERE/cmd" "$STAGE/"
cp "$HERE/go.mod" "$STAGE/"
cp "$HERE/nginx.conf" "$STAGE/"
cp -R "$HERE/web" "$STAGE/"
cp -R "$HERE/deploy" "$STAGE/"
mkdir -p "$STAGE/configs"
cp "$HERE/configs/"*.yaml "$STAGE/configs/" 2>/dev/null || true

# 1. Re-root internal/ under internal/satellite/.
mkdir -p "$STAGE/internal/satellite"
for dir in connector crypto deployment discovery dns01 secrets audit ca credstore policy securefs state; do
    [ -d "$HERE/internal/$dir" ] && cp -R "$HERE/internal/$dir" "$STAGE/internal/satellite/"
done
# api is the Gateway Portal REST API.
[ -d "$HERE/internal/api" ] && cp -R "$HERE/internal/api" "$STAGE/internal/satellite/"
# vsatellite-coordinator declares `package vsatellite`, so the directory name
# has to match the package for the import path to read naturally.
[ -d "$HERE/internal/vsatellite-coordinator" ] && \
    cp -R "$HERE/internal/vsatellite-coordinator" "$STAGE/internal/satellite/vsatellite"
# runtime/*.go is `package satellite` and belongs at the root of internal/satellite.
cp "$HERE/internal/runtime/"*.go "$STAGE/internal/satellite/"

# 2. Core interfaces and common models come from the control plane. Gateway
# config and satellite transport models then override their shared counterparts.
mkdir -p "$STAGE/internal/core"
cp "$CONTROL_PLANE/internal/core/interfaces.go" "$STAGE/internal/core/"
cp -R "$CONTROL_PLANE/pkg" "$STAGE/"
rm -rf "$STAGE/pkg/config"
cp -R "$HERE/pkg/config" "$STAGE/pkg/"
cp "$HERE/pkg/models/satellite.go" "$STAGE/pkg/models/satellite.go"

# go.sum is regenerated by `go mod tidy` inside the Docker build.
: > "$STAGE/go.sum"

tar czf "$OUT" -C "$STAGE" .
echo "wrote $OUT"
tar tzf "$OUT" | grep -E 'internal/satellite/(api|vsatellite)/|internal/satellite/runtime.go|internal/core/' | sort
