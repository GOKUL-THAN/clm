package api

import (
	"fmt"
	"strings"
)

// vsatelliteInstallScript renders the agent installer for a specific enrolment.
//
// The script is generated rather than shipped as a file so the gateway URL and
// the single-use token are baked in: the operator copies one command and does
// not have to hand-edit configuration on the target.
//
// It supports the distributions the estate actually runs — Debian/Ubuntu,
// RHEL/Rocky/Alma/CentOS, Amazon Linux, SUSE and Alpine — by detecting the
// package manager rather than the distribution name, which is what keeps the
// list short and the behaviour predictable on derivatives.
//
// The token is embedded in a root-only file and exchanged for a long-lived agent
// secret on first contact, so the short-lived token does not need to persist.
func vsatelliteInstallScript(gatewayURL, token, gatewayName string) string {
	coordinatorURL := coordinatorEndpoint(gatewayURL)

	return fmt.Sprintf(`#!/bin/sh
# CLM vSatellite agent installer
# Generated by gateway: %s
#
# This script is idempotent: re-running it reinstalls the unit and re-enrols only
# if the local credential is missing.
set -eu

GATEWAY_URL="%s"
COORDINATOR_URL="%s"
ENROL_TOKEN="%s"
INSTALL_DIR="/opt/clm-vsatellite"
CONF_DIR="/etc/clm"
CRED_FILE="$CONF_DIR/vsatellite.cred"
SERVICE="clm-vsatellite"

log()  { printf '[clm] %%s\n' "$1"; }
fail() { printf '[clm] ERROR: %%s\n' "$1" >&2; exit 1; }

[ "$(id -u)" = "0" ] || fail "run as root (prefix the command with sudo)"

# ---------------------------------------------------------------------------
# 1. Detect the platform by package manager, not by distribution name, so
#    derivatives work without a per-distro branch.
# ---------------------------------------------------------------------------
PKG=""
for candidate in apt-get dnf yum zypper apk; do
    if command -v "$candidate" >/dev/null 2>&1; then PKG="$candidate"; break; fi
done
[ -n "$PKG" ] || fail "no supported package manager found (apt-get, dnf, yum, zypper or apk)"

OS_NAME="unknown"
[ -r /etc/os-release ] && . /etc/os-release && OS_NAME="${PRETTY_NAME:-${NAME:-unknown}}"
ARCH="$(uname -m)"
log "host: $(hostname) | os: $OS_NAME | arch: $ARCH | package manager: $PKG"

# ---------------------------------------------------------------------------
# 2. Dependencies. curl and ca-certificates are the only hard requirements.
# ---------------------------------------------------------------------------
install_deps() {
    case "$PKG" in
        apt-get) apt-get update -qq && apt-get install -y -qq curl ca-certificates >/dev/null ;;
        dnf)     dnf install -y -q curl ca-certificates >/dev/null ;;
        yum)     yum install -y -q curl ca-certificates >/dev/null ;;
        zypper)  zypper --non-interactive --quiet install curl ca-certificates >/dev/null ;;
        apk)     apk add --no-cache --quiet curl ca-certificates >/dev/null ;;
    esac
}
if command -v curl >/dev/null 2>&1; then
    log "curl already present"
else
    log "installing dependencies"
    install_deps || fail "dependency installation failed"
fi

# ---------------------------------------------------------------------------
# 3. Reachability. Failing here with a clear message beats a unit that
#    restart-loops after the operator has walked away.
# ---------------------------------------------------------------------------
log "checking gateway reachability"
curl -fsS -m 10 -o /dev/null "$GATEWAY_URL/health" \
    || fail "cannot reach $GATEWAY_URL/health from this host"
log "gateway reachable"

# ---------------------------------------------------------------------------
# 4. Enrol: exchange the single-use token for a durable agent secret.
# ---------------------------------------------------------------------------
mkdir -p "$INSTALL_DIR" "$CONF_DIR"
chmod 700 "$CONF_DIR"

if [ -s "$CRED_FILE" ]; then
    log "existing credential found at $CRED_FILE, skipping enrolment"
else
    log "enrolling with the coordinator"
    AGENT_ID="vsat-$(hostname | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9-' | cut -c1-24)-$(head -c4 /dev/urandom | od -An -tx1 | tr -d ' \n')"
    RESP="$(curl -fsS -m 20 -X POST "$COORDINATOR_URL/vsatellite/enroll" \
        -H 'Content-Type: application/json' \
        -H "X-Agent-Secret: $ENROL_TOKEN" \
        -d "{\"token\":\"$ENROL_TOKEN\",\"agent_id\":\"$AGENT_ID\",\"host\":\"$(hostname)\",\"version\":\"1.0.0\"}" \
        )" || fail "enrolment call failed; the token may be used, expired or revoked"

    SECRET="$(printf '%%s' "$RESP" | sed -n 's/.*"agent_secret"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
    GOT_ID="$(printf '%%s' "$RESP" | sed -n 's/.*"agent_id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
    [ -n "$SECRET" ] || fail "coordinator did not return an agent secret: $RESP"

    umask 077
    printf 'AGENT_ID=%%s\nAGENT_SECRET=%%s\nCOORDINATOR_URL=%%s\n' \
        "$GOT_ID" "$SECRET" "$COORDINATOR_URL" > "$CRED_FILE"
    chmod 600 "$CRED_FILE"
    log "enrolled as $GOT_ID"
fi

# ---------------------------------------------------------------------------
# 5. Heartbeat agent. Kept deliberately small: it reports in and collects
#    queued commands. Certificate work is executed by the gateway today, so the
#    agent's job here is presence and command transport.
# ---------------------------------------------------------------------------
cat > "$INSTALL_DIR/agent.sh" <<'AGENT'
#!/bin/sh
set -eu
. /etc/clm/vsatellite.cred
INTERVAL="${CLM_HEARTBEAT_INTERVAL:-30}"
while :; do
    CERTS=$(ls /etc/ssl/certs/*.pem 2>/dev/null | wc -l | tr -d ' ')
    curl -fsS -m 15 -X POST "$COORDINATOR_URL/vsatellite/heartbeat" \
        -H 'Content-Type: application/json' \
        -H "X-Agent-Secret: $AGENT_SECRET" \
        -d "{\"agent_id\":\"$AGENT_ID\",\"cert_count\":${CERTS:-0},\"version\":\"1.0.0\"}" \
        >/tmp/clm-vsat-last.json 2>/dev/null \
        || echo "[clm] heartbeat failed" >&2
    sleep "$INTERVAL"
done
AGENT
chmod 700 "$INSTALL_DIR/agent.sh"

# ---------------------------------------------------------------------------
# 6. Service supervision: systemd where present, OpenRC on Alpine.
# ---------------------------------------------------------------------------
if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then
    cat > "/etc/systemd/system/$SERVICE.service" <<UNIT
[Unit]
Description=CLM vSatellite Agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=$INSTALL_DIR/agent.sh
Restart=always
RestartSec=10
# The credential is root-only, so the agent runs as root but is otherwise
# confined: it needs no write access outside its own directory.
User=root
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ReadWritePaths=/tmp

[Install]
WantedBy=multi-user.target
UNIT
    systemctl daemon-reload
    systemctl enable "$SERVICE" >/dev/null 2>&1 || true
    systemctl restart "$SERVICE"
    sleep 2
    systemctl is-active --quiet "$SERVICE" \
        && log "service $SERVICE is running" \
        || fail "service failed to start: journalctl -u $SERVICE -n 30"
elif command -v rc-update >/dev/null 2>&1; then
    cat > "/etc/init.d/$SERVICE" <<RC
#!/sbin/openrc-run
name="$SERVICE"
command="$INSTALL_DIR/agent.sh"
command_background=true
pidfile="/run/$SERVICE.pid"
RC
    chmod 755 "/etc/init.d/$SERVICE"
    rc-update add "$SERVICE" default >/dev/null 2>&1 || true
    rc-service "$SERVICE" restart
    log "service $SERVICE started via OpenRC"
else
    log "no supported init system detected; start it manually: $INSTALL_DIR/agent.sh &"
fi

log "done. The agent appears in the gateway portal under vSatellites within ~30s."
`, gatewayName, gatewayURL, coordinatorURL, token)
}

// coordinatorEndpoint derives the agent-facing coordinator URL from the portal
// URL. The coordinator listens on its own port and is not proxied by nginx, so
// the port is swapped rather than a path appended.
func coordinatorEndpoint(gatewayURL string) string {
	trimmed := strings.TrimSuffix(gatewayURL, "/")
	scheme := "http://"
	rest := trimmed
	if i := strings.Index(trimmed, "://"); i >= 0 {
		scheme = trimmed[:i+3]
		rest = trimmed[i+3:]
	}
	if i := strings.Index(rest, "/"); i >= 0 {
		rest = rest[:i]
	}
	if i := strings.LastIndex(rest, ":"); i >= 0 && !strings.Contains(rest[i:], "]") {
		rest = rest[:i]
	}
	return scheme + rest + ":9090"
}
