\set ON_ERROR_STOP on
\getenv app_db_password CLM_APP_DB_PASSWORD
\getenv keycloak_db_password CLM_KEYCLOAK_DB_PASSWORD

SELECT 'CREATE ROLE clm_table_owner NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clm_table_owner')
\gexec
ALTER ROLE clm_table_owner NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;

SELECT 'CREATE ROLE clm_app_role NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clm_app_role')
\gexec
ALTER ROLE clm_app_role NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;

SELECT format(
    'CREATE ROLE clm_app_login LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L',
    :'app_db_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clm_app_login')
\gexec
SELECT format(
    'ALTER ROLE clm_app_login LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L',
    :'app_db_password'
)
\gexec
GRANT clm_app_role TO clm_app_login;
GRANT CONNECT ON DATABASE clm_db TO clm_app_login;
GRANT USAGE ON SCHEMA public TO clm_app_role;

SELECT format(
    'CREATE ROLE clm_keycloak LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L',
    :'keycloak_db_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clm_keycloak')
\gexec
SELECT format(
    'ALTER ROLE clm_keycloak LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD %L',
    :'keycloak_db_password'
)
\gexec

SELECT 'CREATE DATABASE keycloak OWNER clm_keycloak'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'keycloak')
\gexec
ALTER DATABASE keycloak OWNER TO clm_keycloak;

\connect keycloak
GRANT USAGE, CREATE ON SCHEMA public TO clm_keycloak;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO clm_keycloak;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO clm_keycloak;
